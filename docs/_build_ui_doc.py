"""生成《原型设计》Word 文档：界面清单 + 实际界面图 + 说明。"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from _docx_common import (  # noqa: E402
    DOCS,
    body,
    caption,
    heading,
    image,
    new_doc,
    cover_and_toc,
    start_body_section,
    table,
)

FIG = DOCS / "figs"


def main():
    doc = new_doc()
    cover_and_toc(doc, "原型设计", "跨平台消息互通系统（统一收件箱）")
    start_body_section(doc)

    # ---------------------------------------------------------------- 一
    heading(doc, "一、设计原则", 1)
    body(doc, "界面按“一屏之内完成一次完整处理”来设计，不做菜单层层展开的多页结构。"
              "三个判断贯穿始终：")
    body(doc, "第一，左右分栏对应“看哪个”与“做什么”。左边是会话（我是谁在找我），"
              "中间是对话（他说了什么），右边是处理（我要做什么）。"
              "用户不需要理解信息架构，视线从左往右走一遍就是一个完整任务。")
    body(doc, "第二，状态用颜色和位置表达，不用文字解释。紧急的会话置顶并带红标，"
              "未读带蓝点，待处理带橙色计数。同一个信息在三个位置各显示一次（顶栏汇总、"
              "会话项、消息气泡），是为了让用户无论此刻看哪里，都不会漏掉它。")
    body(doc, "第三，破坏性操作都要二次确认，且文案要说后果。"
              "「停用」不说“是否停用”，而说“停用后不再接收该平台消息，凭证会保留”。"
              "说清楚后果，用户才敢点。")

    # ---------------------------------------------------------------- 二
    heading(doc, "二、界面清单", 1)
    body(doc, "系统共 6 个主要界面，全部是单页应用内的视图，没有页面跳转：")

    screens = [
        ("S1", "登录 / 注册", "首次使用显示注册，已有账号显示登录", "未登录用户", "图 3-1"),
        ("S2", "主界面（三栏）", "会话列表 + 消息流 + 处理面板", "日常使用", "图 3-2"),
        ("S3", "发起新消息", "弹窗：选平台、选联系人、写内容", "主动联系某人", "图 3-3"),
        ("S4", "账号与平台", "抽屉：已接入平台、自动回复规则、接入新平台", "配置与维护", "图 3-4"),
        ("S5", "待办", "从消息派生的任务列表", "跟进与排期", "图 3-5"),
        ("S6", "看板", "平均处理时长、收发统计、各平台分布", "复盘与汇报", "图 3-6"),
    ]
    table(doc, ["编号", "界面", "内容", "什么时候用", "图示"], screens,
          widths=[1.4, 3.2, 5.6, 3.2, 1.8])
    caption(doc, "表 2-1 界面清单。六个界面里 S2 是唯一的常驻界面，其余五个都是"
                 "从 S2 打开又回到 S2 的临时视图。这样设计是因为这个产品的使用节奏是"
                 "“频繁看一眼、偶尔处理一下”，不是“长时间停留在一个页面”。"
                 "把配置类操作（S4）收进抽屉而不是独立页面，也是为了不打断阅读。")

    # ---------------------------------------------------------------- 三
    heading(doc, "三、界面详述", 1)

    heading(doc, "3.1 登录与注册（S1）", 2)
    image(doc, FIG / "ui-login.png", width_cm=14.5)
    caption(doc, "图 3-1 首次访问时的注册界面。系统是单用户设计，所以第一次打开看到的是注册"
                 "而不是登录：用户名、口令、确认口令三项，注册完直接进入收件箱，不需要再登一次。"
                 "已有账号时同一位置会切换成登录表单，靠库里是否存在账号自动判断，不需要改配置。"
                 "卡片底部那行小字说明了登录有效期（30 天）与口令错误的后果，"
                 "目的是让使用者知道“这不是每次都要输”。")

    heading(doc, "3.2 主界面（S2）", 2)
    image(doc, FIG / "ui-main.png", width_cm=15.5)
    caption(doc, "图 3-2 主界面三栏布局。左栏是会话列表，每条带平台色条、对方名称、"
                 "最后一条对方消息、以及未读/待处理/紧急三类标记；中栏是消息流，"
                 "入站靠左带圆形头像、出站靠右淡蓝底，按“今天/昨天/日期”分组，"
                 "自己发出的系统回执默认折叠（右上「系统回执 4」可展开）；"
                 "右栏是处理面板，从上到下依次是对方信息、状态与紧急度两个下拉、"
                 "AI 辅助三个按钮、回复框与发送按钮、跨平台转发。"
                 "三栏宽度固定为 308 / 自适应 / 372 像素，中间自适应是因为消息长度不可控，"
                 "两侧固定是因为操作密度稳定。")

    heading(doc, "3.3 发起新消息（S3）", 2)
    image(doc, FIG / "ui-newmsg.png", width_cm=13.5)
    caption(doc, "图 3-3 发起新消息弹窗。三个字段：平台（只列出已接入的）、"
                 "联系人（下拉列出已有会话，也可直接粘 chat_id）、内容（邮箱会多一个主题框）。"
                 "这个界面与“回复”是两条不同路径：回复挂在某条消息下，会带上引用关系；"
                 "发起新消息不依附任何消息，是主动建立联系。两者最终都走出站队列，"
                 "所以在数据上同样是 direction=out 的记录。底部那行提示说明了投递失败会自动重试，"
                 "让用户不必担心网络抖动。")

    heading(doc, "3.4 账号与平台接入（S4）", 2)
    image(doc, FIG / "ui-drawer.png", width_cm=15.5)
    caption(doc, "图 3-4 账号抽屉，三块内容自上而下。最上面是自动回复规则：每条显示关键词、"
                 "适用平台、命中次数、开关与删除按钮，下方一行可以即时新增；"
                 "中间是已接入的平台，显示当前连接状态与「停用」按钮，停用不删凭证，"
                 "所以可以从这里再启用回来；最下面是把平台接进来的表单，"
                 "选平台后会展开对应的分步指引（含跳转链接），"
                 "并明说“填完即生效，不用改 .env、不用重启”。"
                 "把配置做成向导而不是让你去读文档，是因为目标用户不会去开放平台申请应用。")

    heading(doc, "3.5 待办（S5）", 2)
    image(doc, FIG / "ui-todo.png", width_cm=15.5)
    caption(doc, "图 3-5 待办视图。每条待办来自某条具体消息，卡片上显示标题、来源平台、"
                 "当前状态、记录时间与「完成」按钮。右侧面板此时切换为待办页签，"
                 "与左中两栏保持联动；点击完成会把状态写回原平台（可选发一条回执）。"
                 "待办没有做成独立的第二套系统，而是消息的一种派生视图——"
                 "因为用户心里的“待办”本来就是“这条消息我还没处理完”，"
                 "独立建一套任务系统反而要来回对照。")

    heading(doc, "3.6 看板（S6）", 2)
    image(doc, FIG / "ui-stat.png", width_cm=15.5)
    caption(doc, "图 3-6 数据看板。最上方是平均处理时长（从消息入站到回复发出的平均秒数，"
                 "大字号显示并按量级自动切换单位：秒 / 分 / 小时）；下面三格是已回复、"
                 "已关闭、待处理的条数；再下面是出站队列（已发送、排队中、失败）、"
                 "待办（未完成、已完成）与各平台的收发分布。"
                 "这张看板回答的是“我这套流程跑得顺不顺”，所以核心指标选了处理时长"
                 "而不是消息总量——总量只说明忙，时长才说明有没有被卡住。")

    # ---------------------------------------------------------------- 四
    heading(doc, "四、交互约定", 1)
    body(doc, "界面里反复出现的元素都遵循统一规则，用户学会一个就学会了全部：")

    conv = [
        ("平台标签", "灰底小胶囊 + 平台名，飞书蓝、邮箱橙、Telegram 青、采集通道灰", "一眼分清来源"),
        ("状态标签", "待处理橙、处理中蓝、已回复绿、已关闭灰；可点开直接改", "颜色即状态"),
        ("紧急标记", "红底「紧急」，右侧有个 ×，点掉即取消", "紧急是要能撤销的"),
        ("未读提示", "会话名后的蓝色角标显示条数，气泡前的蓝点标记具体哪条", "角标看数量，圆点看位置"),
        ("发送快捷键", "Ctrl+Enter（Mac 为 Cmd+Enter）", "不用移开手去点按钮"),
        ("空状态", "每个区域都有自己的空状态与下一步引导，不留白屏", "空的时候也知道该干什么"),
    ]
    table(doc, ["元素", "规则", "为什么"], conv, widths=[3.0, 8.0, 4.0])
    caption(doc, "表 4-1 交互约定。这些规则的价值在于减少解释成本："
                 "如果一个颜色在不同地方代表不同意思，用户就得每次重新判断。"
                 "表里第六条值得单说——空状态是最容易被忽略的地方，但它是新用户看到的第一个界面。"
                 "我们把每个空状态都写成“现在没有 + 你可以做什么”，"
                 "比如左栏为空时不是“暂无数据”，而是「还没有收到消息 / 去接入平台 →」。")

    # ---------------------------------------------------------------- 五
    heading(doc, "五、响应式与可访问性", 1)
    body(doc, "窗口宽度小于 900 像素时，三栏自动折叠为单栏：先显示会话列表，"
              "点开某个会话后只显示消息流，并在左上角出现「← 列表」返回按钮。"
              "这个断点是按常见手机与窄窗口的宽度定的，不追求在极端尺寸下的完美排布，"
              "只保证“能读、能回”。")
    body(doc, "可访问性方面做了三件事：所有操作按钮都有 title 提示（鼠标悬停可见）；"
              "纯图标按钮配文字标签而不是只有图标；配色对比度按正文可读的标准选取，"
              "状态不单靠颜色区分，也带文字（如「已回复」而不是只有一个绿点）。")

    out = DOCS / "02_原型设计.docx"
    doc.save(out)
    print("saved:", out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
