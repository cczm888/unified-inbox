"""生成《原型设计》Word 文档：界面清单 + 实际界面图 + 说明。"""

import pathlib
import sys

from docx.enum.text import WD_ALIGN_PARAGRAPH

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from _docx_common import (  # noqa: E402
    chapter_lead,
    DOCS,
    body,
    caption,
    heading,
    image,
    new_doc,
    cover_and_toc,
    start_body_section,
    table,
)

FIG = DOCS / "figs"


def main():
    doc = new_doc()
    cover_and_toc(doc, "原型设计", "跨平台消息互通系统（统一收件箱）")
    start_body_section(doc)

    # ---------------------------------------------------------------- 1
    heading(doc, "1. 软件界面清单", 1)
    chapter_lead(doc, "六个界面里只有主界面常驻，其余五个都是从它打开再回来。")

    heading(doc, "1.1 菜单层级", 2)
    body(doc, "系统是单页应用，没有页面跳转，所以「菜单」不是传统左侧导航，而是三栏布局里"
              "三个固定的操作区，加一个未登录时的独立页面。层级关系见下表，"
              "同一一级菜单下的多行共用一格。")

    menu_rows = [
        ("顶栏", "新消息", "S3 发起新消息（弹窗）", "选平台、选联系人、写正文、发送"),
        ("顶栏", "账号", "S4 账号与平台（右侧抽屉）", "已接入平台、自动回复规则、接入新平台、当前账号"),
        ("顶栏", "桌面通知", "—", "开关浏览器通知，仅页面不可见时弹"),
        ("左栏", "平台筛选", "—", "按平台过滤会话，未接入的平台也能筛历史"),
        ("左栏", "搜索框", "—", "按人名、会话名、消息正文搜"),
        ("左栏", "会话列表", "S2 消息区（中栏）", "点开会话，右栏同时切到该会话的处理面板"),
        ("中栏", "消息区", "—", "入站出站同列，按天分组；每条可勾选进批量操作"),
        ("中栏", "拉历史", "—", "用应用身份回捞该会话历史消息（POST /inbox/backfill）"),
        ("中栏", "批量操作条", "—", "勾选后出现在消息区上方：全选、标已读、改状态、调紧急度"),
        ("右栏", "处理（一级页签）", "处理面板", "AI 摘要/草稿、回复、发文件、转待办、改状态、跨会话转发"),
        ("右栏", "待办（一级页签）", "S5 待办列表", "从消息派生的任务，可改状态、可完成"),
        ("右栏", "看板（一级页签）", "S6 数据看板", "平均处理时长、已回复/已关闭/待处理、出站队列、各平台收发"),
        ("独立", "—", "S1 登录 / 注册", "未登录时全部界面替换为此页"),
    ]
    numbered = [(str(i + 1),) + r for i, r in enumerate(menu_rows)]
    tbl = table(doc, ["序号", "一级菜单", "二级菜单", "主要界面", "该界面的主要功能"], numbered,
                widths=[1.1, 2.0, 3.6, 3.9, 4.6], font_size=8)
    # 一级菜单相同的连续行，首列纵向合并（官方：如有一对多情况要学会单元格合并）
    r = 1
    while r <= len(numbered):
        c = numbered[r - 1][1]
        span = 1
        while r + span <= len(numbered) and numbered[r + span - 1][1] == c:
            span += 1
        if span > 1:
            tbl.cell(r, 1).merge(tbl.cell(r + span - 1, 1))
            start_seq = numbered[r - 1][0]
            end_seq = numbered[r + span - 2][0]
            tbl.cell(r, 0).merge(tbl.cell(r + span - 1, 0))
            tbl.cell(r, 0).text = f"{start_seq}–{end_seq}"
            p0 = tbl.cell(r, 0).paragraphs[0]
            p0.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r += span
    caption(doc, "表 1-1 菜单层级与主要界面。三栏里只有中栏（消息区）是常驻主干："
                 "顶栏是全局动作、左栏是导航、右栏是处理区。把配置收进抽屉而不是独立页面，"
                 "是为了不打断阅读。")

    heading(doc, "1.2 界面清单", 2)
    body(doc, "系统共 6 个主要界面，全部是单页应用内的视图，没有页面跳转。")
    screens = [
        ("S1", "登录 / 注册", "首次使用显示注册，已有账号显示登录", "未登录用户", "图 3-1"),
        ("S2", "主界面（三栏）", "会话列表 + 消息流 + 处理面板", "日常使用", "图 3-2"),
        ("S3", "发起新消息", "弹窗：选平台、选联系人、写内容", "主动联系某人", "图 3-3"),
        ("S4", "账号与平台", "抽屉：已接入平台、自动回复规则、接入新平台", "配置与维护", "图 3-4"),
        ("S5", "待办", "从消息派生的任务列表", "跟进与排期", "图 3-5"),
        ("S6", "看板", "平均处理时长、收发统计、各平台分布", "复盘与汇报", "图 3-6"),
    ]
    table(doc, ["编号", "界面", "内容", "什么时候用", "图示"], screens,
          widths=[1.4, 3.2, 5.6, 3.2, 1.8])
    caption(doc, "表 1-2 界面清单。S2 是唯一的常驻界面，其余五个都是从 S2 打开又回到 S2 的临时视图。")

    # ---------------------------------------------------------------- 2
    heading(doc, "2. 界面内容", 1)
    chapter_lead(doc, "逐个界面说明：这一屏给谁看、摆什么、能做什么。")

    heading(doc, "2.1 登录与注册（S1）", 2)
    body(doc, "主要展示内容：居中的单卡片，含用户名、口令、确认口令三个输入框与提交按钮，"
              "底部一行说明登录有效期。主要功能：注册新账号（首次）、登录已有账号、"
              "口令错误时给出明确提示。系统是单用户设计，所以第一次打开看到的是注册而不是登录；"
              "已有账号时同一位置自动切换成登录表单，靠库里是否存在账号判断，不需要改配置。")

    heading(doc, "2.2 主界面（S2）", 2)
    body(doc, "主要展示内容：顶栏（平台在线状态圆点、未读与待处理计数、新消息与账号入口）、"
              "左栏（会话列表，每条带平台色条、对方名称、最后一条消息、未读/待处理/紧急标记）、"
              "中栏（消息流，入站靠左、出站靠右，按今天/昨天/日期分组）、"
              "右栏（处理面板：对方信息、状态与紧急度下拉、AI 辅助、回复框、发文件、跨平台转发）。"
              "主要功能：查询与筛选会话、阅读与搜索消息、回复文本与文件、批量改状态、"
              "引用回复、转待办、拉取历史、跨平台转发。三栏宽度固定为 308 / 自适应 / 372 像素，"
              "中间自适应是因为消息长度不可控，两侧固定是因为操作密度稳定。")

    heading(doc, "2.3 发起新消息（S3）", 2)
    body(doc, "主要展示内容：弹窗三字段——平台（列出已接入的平台）、联系人（输入框带补全，"
              "敲字符列出已有会话，也可直接粘 chat_id）、内容（邮箱多一个主题框）。"
              "主要功能：选平台、选联系人、写正文、发送。它与「回复」是两条不同路径：回复挂在"
              "某条消息下、带引用关系；发起新消息不依附任何消息，是主动建立联系。两者最终都走"
              "出站队列，在数据上同样是 direction=out 的记录。")

    heading(doc, "2.4 账号与平台接入（S4）", 2)
    body(doc, "主要展示内容：右侧抽屉自上而下五块——身份边界说明、飞书账号授权、自动回复规则、"
              "已接入的平台、接入新平台向导。主要功能：授权与刷新状态、增删改自动回复规则"
              "（关键词、适用平台、命中次数、开关）、查看与停用已接入平台、"
              "三步填凭证接入新平台。把配置做成向导而不是让人去读文档，"
              "是因为目标用户不会去开放平台申请应用。")

    heading(doc, "2.5 待办（S5）", 2)
    body(doc, "主要展示内容：卡片列表，每条显示标题、来源平台、当前状态、记录时间与「完成」按钮；"
              "右侧面板此时切换为待办页签，与左中两栏联动。主要功能：查看待办、标记完成、"
              "完成后把状态写回原平台（可选发一条回执）。待办没有做成独立的第二套系统，"
              "而是消息的一种派生视图——因为用户心里的「待办」本来就是「这条消息我还没处理完」。")

    heading(doc, "2.6 看板（S6）", 2)
    body(doc, "主要展示内容：平均处理时长（大字号，按量级自动切换秒/分/小时）、"
              "已回复/已关闭/待处理三格计数、出站队列（已发送、排队中、失败）、"
              "待办（未完成、已完成）、各平台收发分布。主要功能：查看统计、定位积压。"
              "核心指标选处理时长而不是消息总量——总量只说明忙，时长才说明有没有被卡住。")

    # ---------------------------------------------------------------- 3
    heading(doc, "3. 界面设计", 1)
    chapter_lead(doc, "六个界面的实际截图，标注关键位置与设计取舍。")

    heading(doc, "3.1 登录与注册界面", 2)
    image(doc, FIG / "ui-login.png", width_cm=14.5)
    caption(doc, "图 3-1 注册界面。单卡片居中，三个输入框与一个主按钮，"
                 "底部小字说明登录有效期 30 天。")

    heading(doc, "3.2 主界面", 2)
    image(doc, FIG / "ui-main.png", width_cm=15.5)
    caption(doc, "图 3-2 主界面三栏布局。左栏会话列表带平台色条与三类标记，"
                 "中栏消息流入站靠左出站靠右、按天分组，右栏是处理面板，"
                 "标题右侧「拉历史」用于回捞漏掉的消息。")

    heading(doc, "3.3 发起新消息弹窗", 2)
    image(doc, FIG / "ui-newmsg.png", width_cm=13.5)
    caption(doc, "图 3-3 发起新消息弹窗。平台、联系人（带补全）、内容三个字段，"
                 "底部说明投递失败会自动重试。")

    heading(doc, "3.4 账号与原平台接入", 2)
    image(doc, FIG / "ui-drawer.png", width_cm=15.5)
    caption(doc, "图 3-4 账号抽屉。自上而下：自动回复规则（关键词、命中次数、开关）、"
                 "已接入的平台（连接状态与停用）、接入新平台三步表单。"
                 "抽屉最上方还有一段应用身份与用户身份的边界说明。")

    heading(doc, "3.5 待办视图", 2)
    image(doc, FIG / "ui-todo.png", width_cm=15.5)
    caption(doc, "图 3-5 待办视图。每条待办来自某条具体消息，显示标题、来源平台、状态与完成按钮，"
                 "右侧面板同步切到待办页签。")

    heading(doc, "3.6 数据看板", 2)
    image(doc, FIG / "ui-stat.png", width_cm=15.5)
    caption(doc, "图 3-6 数据看板。顶部平均处理时长按量级切换单位，下面依次是三格计数、"
                 "出站队列、待办统计与各平台收发分布。")

    # ---------------------------------------------------------------- 4
    heading(doc, "4. 其他", 1)
    chapter_lead(doc, "全站交互约定、响应式与可访问性，以及 AI 对话过程链接。")

    heading(doc, "4.1 交互约定", 2)
    body(doc, "界面里反复出现的元素都遵循统一规则，用户学会一个就学会了全部。"
              "这些规则的价值在于减少解释成本。")
    conv = [
        ("紧急度", "三档：普通、紧急、非常紧急；紧急及以上会置顶并带红标", "让最该回的那条自己浮上来"),
        ("未读", "蓝色圆点 + 会话计数；点开会话即标已读", "看没看过与处理到哪一步是两件事"),
        ("待处理", "橙色计数，出现在顶栏与会话项", "数量比文字更快传达积压程度"),
        ("状态色", "待处理橙、处理中蓝、已回复绿、已关闭灰", "同一含义全站同色，不按页面变色"),
        ("破坏性操作", "二次确认，文案说明后果（如「停用后不再接收，凭证保留」）", "说清后果用户才敢点"),
        ("空状态", "每种空状态都有引导动作（如「去接入平台」）", "空页面是最容易被放弃的地方"),
    ]
    table(doc, ["元素", "规则", "为什么"], conv, widths=[3.0, 8.0, 4.0])
    caption(doc, "表 4-1 全站交互约定。")

    heading(doc, "4.2 响应式与可访问性", 2)
    body(doc, "窗口宽度小于 900 像素时切成单栏：左栏与中栏互斥显示，"
              "从会话返回列表靠左上角按钮，右栏处理面板改为底部抽屉。"
              "桌面端三栏的最小可用宽度是 1100 像素，再窄就开始挤压消息正文。"
              "可访问性上做到三点：全部可点元素有焦点样式、状态不只用颜色区分（同时有文字或图标）、"
              "关键操作可用键盘完成（Ctrl+Enter 发送、Esc 关闭弹窗）。")

    heading(doc, "4.3 AI 对话过程", 2)
    body(doc, "本项目使用 AI 辅助开发，全部对话过程导出后放在代码仓库的 ai-session-export 目录，"
              "链接：https://github.com/cczm888/unified-inbox/tree/main/ai-session-export 。")

    out = DOCS / "02_原型设计.docx"
    doc.save(out)
    print("saved:", out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
